  const calculateCurveY = (flightLevel: number, x: number) => {
    const lower = [...BUFFET_CURVES]
      .reverse()
      .find((curve) => curve.flightLevel <= flightLevel);
    const upper = BUFFET_CURVES.find(
      (curve) => curve.flightLevel >= flightLevel,
    );
    if (!lower || !upper) return null;
    const readCurve = (points: readonly (readonly [number, number])[]) => {
      const index = points.findIndex(([pointX]) => pointX >= x);
      if (index <= 0)
        return index === 0 && points[0][0] === x ? points[0][1] : null;
      const [x0, y0] = points[index - 1];
      const [x1, y1] = points[index];
      return y0 + ((y1 - y0) * (x - x0)) / (x1 - x0);
    };
    const lowerY = readCurve(lower.points);
    const upperY = readCurve(upper.points);
    if (lowerY === null || upperY === null) return null;
    if (lower === upper) return lowerY;
    const share =
      (flightLevel - lower.flightLevel) /
      (upper.flightLevel - lower.flightLevel);
    return lowerY + (upperY - lowerY) * share;
  };

